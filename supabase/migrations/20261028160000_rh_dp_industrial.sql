-- SYSNQRA ERP INDUSTRIAL — RH / DP e custo de mão de obra
-- Revisão 28/10/2026. Aditivo compatível com as referências existentes de PCP em erp_funcionarios.
begin;

create table if not exists public.erp_funcionarios (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.erp_empresas(id) on delete restrict,
  matricula bigint generated by default as identity,
  nome text not null,
  nome_completo text,
  cpf text,
  rg text,
  data_nascimento date,
  celular text,
  telefone text,
  email text,
  data_admissao date,
  cargo text,
  departamento text not null default 'PRODUCAO_CHAO',
  regime_trabalho text not null default 'CLT',
  turno_trabalho text not null default 'TURNO_1',
  numero_cracha_rfid text,
  salario_nominal numeric(12,2) not null default 0,
  custo_hora_homem numeric(12,4) not null default 0,
  status text not null default 'Ativo',
  status_colaborador text not null default 'Ativo',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.erp_funcionarios add column if not exists empresa_id uuid references public.erp_empresas(id) on delete restrict;
alter table public.erp_funcionarios add column if not exists nome text;
alter table public.erp_funcionarios add column if not exists nome_completo text;
alter table public.erp_funcionarios add column if not exists cpf text;
alter table public.erp_funcionarios add column if not exists rg text;
alter table public.erp_funcionarios add column if not exists data_nascimento date;
alter table public.erp_funcionarios add column if not exists celular text;
alter table public.erp_funcionarios add column if not exists telefone text;
alter table public.erp_funcionarios add column if not exists email text;
alter table public.erp_funcionarios add column if not exists data_admissao date;
alter table public.erp_funcionarios add column if not exists cargo text;
alter table public.erp_funcionarios add column if not exists departamento text not null default 'PRODUCAO_CHAO';
alter table public.erp_funcionarios add column if not exists regime_trabalho text not null default 'CLT';
alter table public.erp_funcionarios add column if not exists turno_trabalho text not null default 'TURNO_1';
alter table public.erp_funcionarios add column if not exists numero_cracha_rfid text;
alter table public.erp_funcionarios add column if not exists salario_nominal numeric(12,2) not null default 0;
alter table public.erp_funcionarios add column if not exists custo_hora_homem numeric(12,4) not null default 0;
alter table public.erp_funcionarios add column if not exists status text not null default 'Ativo';
alter table public.erp_funcionarios add column if not exists status_colaborador text not null default 'Ativo';
alter table public.erp_funcionarios add column if not exists updated_at timestamptz not null default now();

update public.erp_funcionarios
set nome_completo = coalesce(nullif(nome_completo,''), nome),
    nome = coalesce(nullif(nome,''), nome_completo),
    status_colaborador = coalesce(nullif(status_colaborador,''), status, 'Ativo'),
    status = coalesce(nullif(status,''), status_colaborador, 'Ativo')
where nome is not null or nome_completo is not null;

create index if not exists idx_erp_funcionarios_empresa_nome on public.erp_funcionarios (empresa_id, nome);
create unique index if not exists uq_erp_funcionarios_empresa_cpf on public.erp_funcionarios (empresa_id, cpf) where cpf is not null and btrim(cpf) <> '';
create unique index if not exists uq_erp_funcionarios_empresa_rfid on public.erp_funcionarios (empresa_id, numero_cracha_rfid) where numero_cracha_rfid is not null and btrim(numero_cracha_rfid) <> '';

alter table public.erp_funcionarios enable row level security;
drop policy if exists rh_funcionarios_select_tenant on public.erp_funcionarios;
drop policy if exists rh_funcionarios_insert_tenant on public.erp_funcionarios;
drop policy if exists rh_funcionarios_update_tenant on public.erp_funcionarios;
drop policy if exists rh_funcionarios_delete_tenant on public.erp_funcionarios;
create policy rh_funcionarios_select_tenant on public.erp_funcionarios for select to authenticated
  using (public.erp_is_master() or empresa_id = public.erp_current_empresa_id());
create policy rh_funcionarios_insert_tenant on public.erp_funcionarios for insert to authenticated
  with check (empresa_id is not null and empresa_id = public.erp_current_empresa_id());
create policy rh_funcionarios_update_tenant on public.erp_funcionarios for update to authenticated
  using (empresa_id = public.erp_current_empresa_id())
  with check (empresa_id = public.erp_current_empresa_id());
create policy rh_funcionarios_delete_tenant on public.erp_funcionarios for delete to authenticated
  using (empresa_id = public.erp_current_empresa_id());

grant select, insert, update on public.erp_funcionarios to authenticated;
commit;
