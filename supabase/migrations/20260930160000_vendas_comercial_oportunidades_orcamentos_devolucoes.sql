-- Vendas & Comercial: CRM, propostas/orçamentos e RMA.
-- Aplicada no projeto Supabase em 2026-09-30 e versionada para reprodução.

create table if not exists public.erp_vendas_oportunidades (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.erp_empresas(id),
  cliente_id uuid references public.erp_clientes(id),
  titulo text not null,
  valor_estimado numeric(14,2) not null default 0,
  probabilidade numeric(5,2) not null default 0,
  etapa text not null default 'PROSPECCAO',
  responsavel_id uuid references public.erp_usuarios(id),
  proxima_acao text,
  motivo_perda text,
  observacoes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint erp_vendas_oportunidades_probabilidade_ck check (probabilidade between 0 and 100),
  constraint erp_vendas_oportunidades_etapa_ck check (etapa in ('PROSPECCAO','QUALIFICACAO','PROPOSTA','NEGOCIACAO','GANHO','PERDIDO'))
);

create table if not exists public.erp_vendas_orcamentos (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.erp_empresas(id),
  numero bigint generated by default as identity,
  cliente_id uuid not null references public.erp_clientes(id),
  contato text,
  validade date,
  vendedor_id uuid references public.erp_usuarios(id),
  tabela_preco_id uuid references public.erp_tabelas_preco(id),
  condicao_pagamento text,
  status text not null default 'RASCUNHO',
  subtotal numeric(14,2) not null default 0,
  desconto numeric(14,2) not null default 0,
  total numeric(14,2) not null default 0,
  margem_percentual numeric(8,3),
  termos text,
  observacoes text,
  oportunidade_id uuid references public.erp_vendas_oportunidades(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint erp_vendas_orcamentos_status_ck check (status in ('RASCUNHO','ENVIADO','APROVADO','RECUSADO','VENCIDO','CONVERTIDO'))
);

create table if not exists public.erp_vendas_orcamentos_itens (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.erp_empresas(id),
  orcamento_id uuid not null references public.erp_vendas_orcamentos(id) on delete cascade,
  produto_id uuid not null references public.erp_produtos(id),
  quantidade numeric(14,3) not null,
  preco_unitario numeric(14,4) not null,
  desconto_percentual numeric(8,3) not null default 0,
  total numeric(14,2) generated always as (round((quantidade * preco_unitario) * (1 - desconto_percentual / 100), 2)) stored,
  created_at timestamptz not null default now(),
  constraint erp_vendas_orcamentos_itens_qty_ck check (quantidade > 0),
  constraint erp_vendas_orcamentos_itens_price_ck check (preco_unitario >= 0),
  constraint erp_vendas_orcamentos_itens_discount_ck check (desconto_percentual between 0 and 100)
);

create table if not exists public.erp_vendas_devolucoes (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.erp_empresas(id),
  numero bigint generated by default as identity,
  cliente_id uuid not null references public.erp_clientes(id),
  nfe_original_id uuid references public.fiscal_nfes(id),
  tipo text not null default 'DEVOLUCAO',
  motivo text not null,
  status text not null default 'ABERTA',
  tratamento_sgq text not null default 'QUARENTENA',
  valor_credito numeric(14,2) not null default 0,
  observacoes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint erp_vendas_devolucoes_tipo_ck check (tipo in ('DEVOLUCAO','TROCA','GARANTIA_RMA')),
  constraint erp_vendas_devolucoes_status_ck check (status in ('ABERTA','EM_ANALISE','APROVADA','REJEITADA','CONCLUIDA')),
  constraint erp_vendas_devolucoes_tratamento_ck check (tratamento_sgq in ('QUARENTENA','RETRABALHO','SUCATA','LIBERACAO'))
);

create table if not exists public.erp_vendas_devolucoes_itens (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.erp_empresas(id),
  devolucao_id uuid not null references public.erp_vendas_devolucoes(id) on delete cascade,
  produto_id uuid not null references public.erp_produtos(id),
  quantidade numeric(14,3) not null,
  motivo_item text,
  acao_sgq text,
  valor_unitario numeric(14,4) not null default 0,
  created_at timestamptz not null default now(),
  constraint erp_vendas_devolucoes_itens_qty_ck check (quantidade > 0)
);

alter table public.erp_vendas_oportunidades enable row level security;
alter table public.erp_vendas_orcamentos enable row level security;
alter table public.erp_vendas_orcamentos_itens enable row level security;
alter table public.erp_vendas_devolucoes enable row level security;
alter table public.erp_vendas_devolucoes_itens enable row level security;

create policy erp_tenant_vendas_oportunidades on public.erp_vendas_oportunidades for all to authenticated using ((empresa_id = erp_current_empresa_id()) or erp_is_master()) with check ((empresa_id = erp_current_empresa_id()) or erp_is_master());
create policy erp_tenant_vendas_orcamentos on public.erp_vendas_orcamentos for all to authenticated using ((empresa_id = erp_current_empresa_id()) or erp_is_master()) with check ((empresa_id = erp_current_empresa_id()) or erp_is_master());
create policy erp_tenant_vendas_orcamentos_itens on public.erp_vendas_orcamentos_itens for all to authenticated using ((empresa_id = erp_current_empresa_id()) or erp_is_master()) with check ((empresa_id = erp_current_empresa_id()) or erp_is_master());
create policy erp_tenant_vendas_devolucoes on public.erp_vendas_devolucoes for all to authenticated using ((empresa_id = erp_current_empresa_id()) or erp_is_master()) with check ((empresa_id = erp_current_empresa_id()) or erp_is_master());
create policy erp_tenant_vendas_devolucoes_itens on public.erp_vendas_devolucoes_itens for all to authenticated using ((empresa_id = erp_current_empresa_id()) or erp_is_master()) with check ((empresa_id = erp_current_empresa_id()) or erp_is_master());

grant select, insert, update, delete on public.erp_vendas_oportunidades, public.erp_vendas_orcamentos, public.erp_vendas_orcamentos_itens, public.erp_vendas_devolucoes, public.erp_vendas_devolucoes_itens to authenticated;
